import { createPublicKey, verify } from 'node:crypto';
import { PRO_FEATURES, type LicenseInfo } from '@s3ndless/shared';
import { z } from 'zod';
import { LICENSE_PUBLIC_KEYS } from './keys.js';

/**
 * License keys are compact JWS tokens signed with Ed25519:
 *   base64url(header) . base64url(payload) . base64url(signature)
 * They are verified offline against public keys compiled into the app. There is no phone-home.
 */

export const LICENSE_TYPE = 'S3NDLESS-LICENSE';
const GRACE_DAYS = 14;

const headerSchema = z.object({ alg: z.literal('EdDSA'), typ: z.literal(LICENSE_TYPE), kid: z.string().min(1) });

export const licensePayloadSchema = z.object({
  iss: z.literal('s3ndless'),
  lid: z.string().min(1).max(100),
  licensee: z.string().min(1).max(200),
  edition: z.literal('pro'),
  features: z.array(z.enum(PRO_FEATURES)).min(1),
  iat: z.number().int(),
  exp: z.number().int(),
});
export type LicensePayload = z.infer<typeof licensePayloadSchema>;

export type LicenseResult =
  | { ok: true; info: LicenseInfo; warning?: string }
  | { ok: false; error: string };

function decodeJson(part: string): unknown {
  return JSON.parse(Buffer.from(part, 'base64url').toString('utf8'));
}

const developmentKeys: Record<string, string> = {};

/**
 * Local development only (`S3NDLESS_DEV_PRO=1 npm run dev`): trusts a throwaway key generated by the
 * dev server process. Never called by the Lambda handlers.
 */
export function trustDevelopmentKey(kid: string, publicKeyPem: string): void {
  developmentKeys[`dev:${kid}`] = publicKeyPem;
}

export function verifyLicense(
  key: string,
  now: number,
  keys: Readonly<Record<string, string>> = { ...LICENSE_PUBLIC_KEYS, ...developmentKeys },
): LicenseResult {
  const parts = key.trim().split('.');
  if (parts.length !== 3) return { ok: false, error: 'This is not an S3ndless license key' };
  const [h, p, s] = parts as [string, string, string];

  let header: z.infer<typeof headerSchema>;
  let payload: LicensePayload;
  try {
    header = headerSchema.parse(decodeJson(h));
    payload = licensePayloadSchema.parse(decodeJson(p));
  } catch {
    return { ok: false, error: 'This license key is malformed' };
  }

  const pem = keys[header.kid];
  if (!pem) return { ok: false, error: 'This license key was not issued for this version of S3ndless' };
  let valid = false;
  try {
    valid = verify(null, Buffer.from(`${h}.${p}`), createPublicKey(pem), Buffer.from(s, 'base64url'));
  } catch {
    valid = false;
  }
  if (!valid) return { ok: false, error: 'This license key has an invalid signature' };

  const expiresAt = payload.exp * 1000;
  const expiry = new Date(expiresAt).toISOString().slice(0, 10);
  if (now > expiresAt + GRACE_DAYS * 86_400_000) {
    return { ok: false, error: `This license expired on ${expiry}` };
  }
  const info: LicenseInfo = {
    licenseId: payload.lid,
    licensee: payload.licensee,
    edition: payload.edition,
    features: payload.features,
    expiresAt: new Date(expiresAt).toISOString(),
  };
  if (now > expiresAt) {
    return { ok: true, info, warning: `This license expired on ${expiry}. Pro features stay on for ${GRACE_DAYS} days.` };
  }
  return { ok: true, info };
}
